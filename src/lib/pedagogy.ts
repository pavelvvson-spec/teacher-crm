// Повних років на сьогодні (враховує день і місяць, якщо відомі)
export function ageYears(s: { birthYear?: number | null; birthDay?: number | null; birthMonth?: number | null }) {
  if (!s.birthYear) return null;
  const now = new Date();
  const kyiv = new Intl.DateTimeFormat("en-CA", { timeZone: "Europe/Kyiv", year: "numeric", month: "numeric", day: "numeric" })
    .formatToParts(now)
    .reduce<Record<string, number>>((acc, p) => (p.type !== "literal" ? { ...acc, [p.type]: Number(p.value) } : acc), {});
  let age = kyiv.year - s.birthYear;
  if (s.birthMonth && s.birthDay) {
    if (kyiv.month < s.birthMonth || (kyiv.month === s.birthMonth && kyiv.day < s.birthDay)) age -= 1;
  }
  return age;
}

export function ageInfo(s: {
  birthYear?: number | null;
  birthDay?: number | null;
  birthMonth?: number | null;
  isAdult?: boolean | null;
  gender?: string | null;
}): string {
  const f = s.gender === "F";
  // Підказка ШІ про стать — щоб писав про учня/ученицю в правильному роді
  const genderNote =
    s.gender === "F"
      ? "; стать: дівчина — пиши про неї в жіночому роді"
      : s.gender === "M"
        ? "; стать: хлопець — пиши про нього в чоловічому роді"
        : "";
  if (s.birthYear) {
    const age = ageYears(s) ?? 0;
    const group =
      age <= 6
        ? "дошкільня"
        : age <= 10
          ? f ? "молодша школярка" : "молодший школяр"
          : age <= 15
            ? f ? "дівчина-підліток" : "підліток"
            : age <= 17
              ? f ? "старшокласниця" : "старшокласник"
              : f ? "доросла" : "дорослий";
    return `${age} р. (${group})${genderNote}`;
  }
  if (s.isAdult) return `${f ? "доросла" : "дорослий"}${genderNote}`;
  return `невідомо${genderNote}`;
}

// Додаток до системної інструкції: загальні принципи + методика вчительки
export async function methodContext(): Promise<string> {
  let methodology: string | null = null;
  try {
    const settings = await prisma.settings.findFirst({ select: { methodology: true } });
    methodology = settings?.methodology?.trim() || null;
  } catch {
    methodology = null;
  }
  return `

${PEDAGOGY}
${
  methodology
    ? `
МЕТОДИКА ЦІЄЇ ВЧИТЕЛЬКИ (її власні правила — мають ПРІОРИТЕТ над загальними принципами):
${methodology.slice(0, 12000)}`
    : ""
}`;
}
